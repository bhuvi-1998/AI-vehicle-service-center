-- Vehicle Service Center
-- PostgreSQL schema for a fresh, empty Supabase database.
-- This file creates tables only. It does not migrate local MySQL records.

-- 1. Administrator accounts
CREATE TABLE IF NOT EXISTS admins (
    admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) DEFAULT 'admin',
    CONSTRAINT uq_admin_email UNIQUE (email)
);

-- 2. Customer accounts and email verification
CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    email VARCHAR(100) DEFAULT NULL,
    address VARCHAR(255) DEFAULT NULL,
    password_hash VARCHAR(255) DEFAULT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    verification_token_hash CHAR(64) DEFAULT NULL,
    verification_expires_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
    CONSTRAINT uq_customer_phone UNIQUE (phone),
    CONSTRAINT uq_customer_email UNIQUE (email)
);

-- 3. Services
CREATE TABLE IF NOT EXISTS services (
    service_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(100) NOT NULL,
    description VARCHAR(255) DEFAULT NULL,
    vehicle_type VARCHAR(20) NOT NULL DEFAULT 'Car',
    price NUMERIC(10,2) NOT NULL,
    CONSTRAINT uq_service_name UNIQUE (service_name)
);

-- 4. Technicians
CREATE TABLE IF NOT EXISTS technicians (
    technician_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    specialization VARCHAR(100) DEFAULT NULL,
    vehicle_type VARCHAR(20) NOT NULL DEFAULT 'All',
    experience INTEGER DEFAULT NULL,
    CONSTRAINT uq_technician_phone UNIQUE (phone)
);

-- 5. Customer vehicles
CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL DEFAULT 'Car',
    vehicle_number VARCHAR(20) NOT NULL,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    manufacture_year INTEGER DEFAULT NULL,
    CONSTRAINT uq_vehicle_number UNIQUE (vehicle_number),
    CONSTRAINT fk_vehicles_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
);

CREATE INDEX IF NOT EXISTS idx_vehicles_customer
    ON vehicles(customer_id);

-- 6. Spare-parts inventory
CREATE TABLE IF NOT EXISTS parts (
    part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_name VARCHAR(100) NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL DEFAULT 'All',
    part_number VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(10,2) NOT NULL,
    CONSTRAINT uq_part_name UNIQUE (part_name),
    CONSTRAINT uq_part_number UNIQUE (part_number)
);

-- 7. Appointments
CREATE TABLE IF NOT EXISTS appointments (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    vehicle_id INTEGER NOT NULL,
    service_id INTEGER NOT NULL,
    technician_id INTEGER DEFAULT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_appointments_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id),
    CONSTRAINT fk_appointments_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES vehicles(vehicle_id),
    CONSTRAINT fk_appointments_service
        FOREIGN KEY (service_id)
        REFERENCES services(service_id),
    CONSTRAINT fk_appointments_technician
        FOREIGN KEY (technician_id)
        REFERENCES technicians(technician_id)
);

CREATE INDEX IF NOT EXISTS idx_appointments_customer
    ON appointments(customer_id);
CREATE INDEX IF NOT EXISTS idx_appointments_vehicle
    ON appointments(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_appointments_service
    ON appointments(service_id);
CREATE INDEX IF NOT EXISTS idx_appointments_technician
    ON appointments(technician_id);

-- 8. Service estimates
CREATE TABLE IF NOT EXISTS estimates (
    estimate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL,
    estimate_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    service_name VARCHAR(100) NOT NULL,
    service_amount NUMERIC(10,2) NOT NULL,
    parts_amount NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10,2) NOT NULL,
    notes TEXT,
    CONSTRAINT fk_estimates_appointment
        FOREIGN KEY (appointment_id)
        REFERENCES appointments(appointment_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_estimates_appointment
    ON estimates(appointment_id);

-- 9. Parts included in estimates
CREATE TABLE IF NOT EXISTS estimate_parts (
    estimate_part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estimate_id INTEGER NOT NULL,
    part_id INTEGER NOT NULL,
    part_name VARCHAR(100) NOT NULL,
    part_number VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    line_total NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_estimate_parts_estimate
        FOREIGN KEY (estimate_id)
        REFERENCES estimates(estimate_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_estimate_parts_part
        FOREIGN KEY (part_id)
        REFERENCES parts(part_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_estimate_parts_estimate
    ON estimate_parts(estimate_id);
CREATE INDEX IF NOT EXISTS idx_estimate_parts_part
    ON estimate_parts(part_id);

-- 10. Final invoices
CREATE TABLE IF NOT EXISTS invoices (
    invoice_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL,
    invoice_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    service_name VARCHAR(100) NOT NULL,
    service_amount NUMERIC(10,2) NOT NULL,
    parts_amount NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10,2) NOT NULL,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    payment_method VARCHAR(30) DEFAULT NULL,
    notes TEXT,
    CONSTRAINT uq_invoice_appointment UNIQUE (appointment_id),
    CONSTRAINT fk_invoices_appointment
        FOREIGN KEY (appointment_id)
        REFERENCES appointments(appointment_id)
        ON DELETE RESTRICT
);

-- 11. Parts included in invoices
CREATE TABLE IF NOT EXISTS invoice_parts (
    invoice_part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id INTEGER NOT NULL,
    part_id INTEGER NOT NULL,
    part_name VARCHAR(100) NOT NULL,
    part_number VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    line_total NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_invoice_parts_invoice
        FOREIGN KEY (invoice_id)
        REFERENCES invoices(invoice_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_invoice_parts_part
        FOREIGN KEY (part_id)
        REFERENCES parts(part_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_invoice_parts_invoice
    ON invoice_parts(invoice_id);
CREATE INDEX IF NOT EXISTS idx_invoice_parts_part
    ON invoice_parts(part_id);

-- 12. Password reset tokens
CREATE TABLE IF NOT EXISTS password_reset_tokens (
    reset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type VARCHAR(10) NOT NULL,
    account_id INTEGER NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    used_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_token UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_password_reset_account
    ON password_reset_tokens(account_type, account_id);
CREATE INDEX IF NOT EXISTS idx_password_reset_expiry
    ON password_reset_tokens(expires_at);
